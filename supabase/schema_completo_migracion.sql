CREATE TABLE IF NOT EXISTS public.transporte_operaciones (
  id uuid NOT NULL DEFAULT uuid_generate_v4(),
  ruta_id uuid NOT NULL,
  escuela_codigo text NOT NULL CHECK (escuela_codigo = ANY (ARRAY['sb'::text, 'lb'::text])),
  fecha date NOT NULL DEFAULT CURRENT_DATE,
  sentido text NOT NULL CHECK (sentido = ANY (ARRAY['Casa - Escuela'::text, 'Escuela - Casa'::text])),
  estado text NOT NULL CHECK (estado = ANY (ARRAY['Programada'::text, 'En Ruta'::text, 'Finalizada'::text])),
  ubicacion_actual text,
  ultima_actualizacion timestamp with time zone NOT NULL DEFAULT timezone('utc'::text, now()),
  historial_paradas jsonb DEFAULT '{}'::jsonb,
  CONSTRAINT transporte_operaciones_pkey PRIMARY KEY (id),
  CONSTRAINT transporte_operaciones_ruta_id_fkey FOREIGN KEY (ruta_id) REFERENCES public.transporte_rutas(id) ON DELETE CASCADE
