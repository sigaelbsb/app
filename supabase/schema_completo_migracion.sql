);

CREATE TABLE IF NOT EXISTS public.transporte_paradas (
  id uuid NOT NULL DEFAULT uuid_generate_v4(),
  escuela_codigo text CHECK (escuela_codigo = ANY (ARRAY['sb'::text, 'lb'::text])),
